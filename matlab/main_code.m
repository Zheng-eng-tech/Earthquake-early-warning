                snr_location = mean(gate_background_snr_db);
                h_location = mean(gate_background_H);
                energy_location = mean(gate_background_energy_db);
                snr_scale = std(gate_background_snr_db, 0);
                h_scale = std(gate_background_H, 0);
                energy_scale = std(gate_background_energy_db, 0);

            case 'median_mad'
                snr_location = median(gate_background_snr_db);
                h_location = median(gate_background_H);
                energy_location = median(gate_background_energy_db);
                snr_scale = 1.4826 * median(abs( ...
                    gate_background_snr_db - snr_location));
                h_scale = 1.4826 * median(abs( ...
                    gate_background_H - h_location));
                energy_scale = 1.4826 * median(abs( ...
                    gate_background_energy_db - energy_location));

            otherwise
                error(['Unsupported light_gate_adaptive_method: %s. ' ...
                       'Use ''median_mad'' or ''mean_std''.'], ...
                      light_gate_adaptive_method);
        end

        snr_scale = max(snr_scale, light_gate_snr_scale_floor_db);
        h_scale = max(h_scale, light_gate_h_scale_floor);
        energy_scale = max(energy_scale, light_gate_energy_scale_floor_db);
        gate_snr_threshold_db = ...
            snr_location + light_gate_snr_k * snr_scale;
        gate_h_threshold = h_location - light_gate_h_k * h_scale;
        gate_energy_threshold_db = ...
            energy_location + light_gate_energy_k * energy_scale;
