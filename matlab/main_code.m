    prob_n = probability_matrix(1, 1);
    prob_p = probability_matrix(1, 2);
    prob_s = probability_matrix(1, 3);
end

function [R, lambda] = calculate_rectilinearity_v2( ...
    st_window, Fs, window_sec, fmin, fmax)
%CALCULATE_RECTILINEARITY_V2
% Calculate Jurkevics-style rectilinearity from the most recent
% part of a three-component window.
%
% Component order is E, N, Z. Eigenvalues do not depend on
% component ordering, provided the three channels are aligned.

    n_available = min([ ...
        length(st_window(1).d), ...
        length(st_window(2).d), ...
        length(st_window(3).d)]);

    n_pol = round(window_sec * Fs);

    if n_available < n_pol
        R = NaN;
        lambda = [NaN, NaN, NaN];
        return;
    end

    first_index = n_available - n_pol + 1;

    E = double(st_window(1).d(first_index:n_available));
    N = double(st_window(2).d(first_index:n_available));
    Z = double(st_window(3).d(first_index:n_available));

    % Remove mean and linear trend separately for each component
    E = detrend(E(:), 'linear');
    N = detrend(N(:), 'linear');
    Z = detrend(Z(:), 'linear');

    % Fourth-order Butterworth band-pass filtering
    normalized_band = [fmin, fmax] / (Fs / 2);

    [b, a] = butter( ...
        4, ...
        normalized_band, ...
        'bandpass');

    E = filtfilt(b, a, E);
    N = filtfilt(b, a, N);
    Z = filtfilt(b, a, Z);

    % Rows are components; columns are time samples
    X = [E.'; N.'; Z.'];

    % Three-component covariance matrix
    C = cov(X.');

    % Symmetric eigendecomposition
    C = (C + C.') / 2;

    eigenvalues = real(eig(C));

    % Jurkevics notation: lambda1 >= lambda2 >= lambda3
    lambda = sort(eigenvalues, 'descend').';

    if lambda(1) <= eps
        R = NaN;
        return;
    end

    R = 1.0 ...
        - (lambda(2) + lambda(3)) ...
        / (2.0 * lambda(1));

    % Protect against tiny numerical excursions
    R = max(0.0, min(1.0, real(R)));
end

function H = calculate_polarization_entropy(lambda)
%CALCULATE_POLARIZATION_ENTROPY
% Calculate normalized polarization entropy from the three
% covariance eigenvalues.
%
% H is in the range [0, 1]:
% H close to 0: variance is concentrated in one principal direction.
% H close to 1: variance is distributed across three directions.

    lambda = double(real(lambda(:)));

    % Reject invalid input
    if numel(lambda) ~= 3 || any(~isfinite(lambda))
        H = NaN;
        return;
    end

    % Remove tiny negative eigenvalues caused by floating-point error
    negative_tolerance = ...
        1e-12 * max(1.0, max(abs(lambda)));

    tiny_negative = ...
        lambda < 0 & lambda >= -negative_tolerance;

    lambda(tiny_negative) = 0;

    % A clearly negative eigenvalue indicates invalid input
    if any(lambda < 0)
        H = NaN;
        return;
    end

    lambda_sum = sum(lambda);

    if lambda_sum <= eps
        H = NaN;
        return;
    end

    % Normalized eigenvalues
    p = lambda / lambda_sum;

    % Use the convention 0*log(0) = 0
    positive_p = p > 0;

    H = -sum( ...
        p(positive_p) .* log(p(positive_p))) ...
        / log(3.0);

    % Protect against tiny floating-point excursions
    H = max(0.0, min(1.0, real(H)));
end

function [stp_power, ltp_power, snr_db] = ...
    calculate_stp_ltp_snr( ...
        st_window, Fs, stp_sec, ltp_sec, fmin, fmax)
%CALCULATE_STP_LTP_SNR
% Calculate dynamic three-component STP/LTP SNR.
%
% The current E3WS window is divided into:
%
%   LTP: the long interval immediately before the STP interval
%   STP: the most recent short interval at the end of the window
%
% The two intervals do not overlap.

    stp_power = NaN;
    ltp_power = NaN;
    snr_db = NaN;

    n_available = min([ ...
        length(st_window(1).d), ...
        length(st_window(2).d), ...
        length(st_window(3).d)]);

    n_stp = round(stp_sec * Fs);
    n_ltp = round(ltp_sec * Fs);
    n_required = n_stp + n_ltp;

    if n_stp < 2 || n_ltp < 2 || n_available < n_required
        return;
    end

    % Use the most recent STP + LTP samples
    first_index = n_available - n_required + 1;

    E = double( ...
        st_window(1).d(first_index:n_available));

    N = double( ...
        st_window(2).d(first_index:n_available));

    Z = double( ...
        st_window(3).d(first_index:n_available));

    E = E(:);
    N = N(:);
    Z = Z(:);

    % Remove linear trends
    E = detrend(E, 'linear');
    N = detrend(N, 'linear');
    Z = detrend(Z, 'linear');

    % Apply the same band-pass filtering used by polarization analysis
    normalized_band = [fmin, fmax] / (Fs / 2);

    if normalized_band(1) <= 0 || ...
            normalized_band(2) >= 1 || ...
            normalized_band(1) >= normalized_band(2)
        return;
    end

    [b, a] = butter( ...
        4, ...
        normalized_band, ...
        'bandpass');

    E = filtfilt(b, a, E);
    N = filtfilt(b, a, N);
    Z = filtfilt(b, a, Z);

    % Combined instantaneous three-component power
    power_3c = E.^2 + N.^2 + Z.^2;

    % Non-overlapping LTP and STP intervals
    ltp_indices = 1:n_ltp;
    stp_indices = (n_ltp + 1):(n_ltp + n_stp);

    ltp_power = mean(power_3c(ltp_indices));
    stp_power = mean(power_3c(stp_indices));

    ltp_power = real(double(ltp_power));
    stp_power = real(double(stp_power));

    if ~isfinite(ltp_power) || ...
            ~isfinite(stp_power) || ...
            ltp_power <= eps || ...
            stp_power <= 0

        stp_power = NaN;
        ltp_power = NaN;
        snr_db = NaN;
        return;
    end

    snr_db = 10.0 * log10( ...
        stp_power / ltp_power);

    snr_db = real(double(snr_db));
end

