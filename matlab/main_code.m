function [prob_n, prob_p, prob_s] = calculate_det_probability_for_window( ...
        st_process, window_index, sliding_sec, window_sec, Fs, N_total, ...
        pb_inst, pzfile, fmin, fmax, DET_pb, np)
    t1_s = window_index * sliding_sec;
    t2_s = t1_s + window_sec;
    idx1 = floor(t1_s * Fs) + 1;
    idx2 = min(floor(t2_s * Fs) + 1, N_total);
    if idx1 < 1 || idx1 > idx2
        error('Invalid retrospective DET window index: %d.', window_index);
    end

    st_window = st_process;
    st_window(1).d = st_process(1).d(idx1:idx2);
    st_window(2).d = st_process(2).d(idx1:idx2);
    st_window(3).d = st_process(3).d(idx1:idx2);

    [FV, ~] = st_FV_final(st_window, pb_inst, pzfile, fmin, fmax, '');
    FV = real(double(FV(:).'));
    FV_py = np.array(FV);
    FV_py = FV_py.reshape(int32(1), int32(numel(FV)));
    probability_py = DET_pb.predict_proba(FV_py);
    probability_vector = double(py.array.array('d', ...
        py.numpy.nditer(probability_py)));
