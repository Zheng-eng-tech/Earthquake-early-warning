            3 + c_mag, ...
            reg_start_s, ...
            reg_end_s, ...
            reg_idx1, ...
            reg_idx2, ...
            npts_reg, ...
            FV45]; %#ok<AGROW>

        %% =========================================================
        % MAG, DIS and DEP model prediction
        %
        % Python:
        % MAG_pb_predict = MAG_pb[c_mag].predict(FV45)[0]
        % DIS_pb_predict = DIS_pb[c_mag].predict(FV45)[0]
        % DEP_pb_predict = DEP_pb[c_mag].predict(FV45)[0]
        %% =========================================================
        
        model_index = c_mag + 1;
        
        % Convert 1 x 140 MATLAB FV45 into a 1 x 140 NumPy array
        FV45_py = np.array(FV45);
        
        FV45_py = FV45_py.reshape( ...
            int32(1), ...
            int32(numel(FV45)));
        
        %% MAG prediction
        
        mag_predict_py = ...
            MAG_pb{model_index}.predict(FV45_py);
        
        mag_predict_vec = double( ...
            py.array.array( ...
                'd', ...
                py.numpy.nditer(mag_predict_py)));
        
        MAG_pb_predict = mag_predict_vec(1);
        
        %% DIS prediction
        
        dis_predict_py = ...
            DIS_pb{model_index}.predict(FV45_py);
        
        dis_predict_vec = double( ...
            py.array.array( ...
                'd', ...
                py.numpy.nditer(dis_predict_py)));
        
        DIS_pb_predict = dis_predict_vec(1);
        
        %% DEP prediction
        
        dep_predict_py = ...
            DEP_pb{model_index}.predict(FV45_py);
        
        dep_predict_vec = double( ...
            py.array.array( ...
                'd', ...
                py.numpy.nditer(dep_predict_py)));
        
        DEP_pb_predict = dep_predict_vec(1);
        %% Save first 3-second magnitude

        if c_mag == 0
            MAG_3s = MAG_pb_predict;
        end
        
        %% Save prediction results
        
        SOURCE_PRED_rows = [SOURCE_PRED_rows; ...
            c_mag, ...
            3 + c_mag, ...
            reg_start_s, ...
            reg_end_s, ...
            npts_reg, ...
            MAG_pb_predict, ...
            DIS_pb_predict, ...
            DEP_pb_predict]; %#ok<AGROW>

        runtime_source_parameter_sec = ...
            runtime_source_parameter_sec + toc(t_source_parameter);


        %% =========================================================
        % BAZ prediction
        %
        % Python:
        % if c_mag <= n_models_baz - 1:
        %     BAZ_cos = BAZ_cos_pb[c_mag].predict(FV45)[0]
        %     BAZ_sin = BAZ_sin_pb[c_mag].predict(FV45)[0]
        %     BAZ = atan2(BAZ_sin, BAZ_cos) * 180 / pi
        %% =========================================================
        
        if c_mag <= n_models_baz - 1

            % Time: BAZ cosine/sine prediction and location inversion.
            t_baz_location = tic;
        
            %% BAZ cosine prediction
        
            baz_cos_predict_py = ...
                BAZ_cos_pb.predict(FV45_py);
        
            baz_cos_predict_vec = double( ...
                py.array.array( ...
                    'd', ...
                    py.numpy.nditer(baz_cos_predict_py)));
        
            BAZ_pb_cos_predict = ...
                baz_cos_predict_vec(1);
        
            %% BAZ sine prediction
        
            baz_sin_predict_py = ...
                BAZ_sin_pb.predict(FV45_py);
        
            baz_sin_predict_vec = double( ...
                py.array.array( ...
                    'd', ...
                    py.numpy.nditer(baz_sin_predict_py)));
        
            BAZ_pb_sin_predict = ...
                baz_sin_predict_vec(1);
        
            %% Convert cosine and sine into BAZ angle
        
            % Exact counterpart of Python:
            % np.arctan2(sin, cos) * 180 / np.pi
            BAZ_pb_predict = ...
                atan2( ...
                    BAZ_pb_sin_predict, ...
                    BAZ_pb_cos_predict) ...
                * 180 / pi;

            %% =========================================================
            % Predicted earthquake location
            %
            % Python:
            % eq_lat, eq_lon = pb_utils.pb_getpoint( ...
            %     sta_lat, ...
            %     sta_lon, ...
            %     DIS_pb_predict, ...
            %     BAZ_pb_predict)
            %% =========================================================
            
            [eq_lat_raw, eq_lon_raw] = ...
                vincenty_destination_wgs84( ...
                    sta_lat, ...
                    sta_lon, ...
                    DIS_pb_predict, ...
                    BAZ_pb_predict);
            
            % Python:
            % eq_lat = round(eq_lat, 6)
            % eq_lon = round(eq_lon, 6)
            
            eq_lat = round(eq_lat_raw, 6);
            eq_lon = round(eq_lon_raw, 6);
            %% Keep 3-second BAZ and location

            latest_BAZ_prediction = ...
                BAZ_pb_predict;
            
            latest_eq_lat = eq_lat;
            latest_eq_lon = eq_lon;
                    
            %% Save BAZ debug result
        
            BAZ_PRED_rows = [BAZ_PRED_rows; ...
                c_mag, ...
                3 + c_mag, ...
                reg_start_s, ...
                reg_end_s, ...
                npts_reg, ...
                BAZ_pb_cos_predict, ...
                BAZ_pb_sin_predict, ...
                BAZ_pb_predict]; %#ok<AGROW>
        
            fprintf(['BAZ prediction: c_mag=%d, ' ...
                     'cos=%.17g, sin=%.17g, ' ...
                     'BAZ=%.17g degrees\n'], ...
                c_mag, ...
                BAZ_pb_cos_predict, ...
                BAZ_pb_sin_predict, ...
                BAZ_pb_predict);

            %% Save location prediction for debugging

            LOCATION_PRED_rows = [LOCATION_PRED_rows; ...
                c_mag, ...
                3 + c_mag, ...
                sta_lat, ...
                sta_lon, ...
                DIS_pb_predict, ...
                BAZ_pb_predict, ...
                eq_lat, ...
                eq_lon]; %#ok<AGROW>
            
            fprintf(['LOCATION prediction: ' ...
                     'station=(%.6f, %.6f), ' ...
                     'distance=%.17g km, ' ...
                     'BAZ=%.17g deg, ' ...
                     'earthquake=(%.6f, %.6f)\n'], ...
                sta_lat, ...
                sta_lon, ...
                DIS_pb_predict, ...
                BAZ_pb_predict, ...
                eq_lat, ...
                eq_lon);

            runtime_baz_location_sec = ...
                runtime_baz_location_sec + toc(t_baz_location);
        end

        %% =========================================================
        % Save one final source-result row
        %% =========================================================
        
        if flag_trackmag && flag_writefile
        
            if isnat(P_arrival_utc)
                error('P_arrival_utc has not been calculated.');
            end
        
            if isnan(latest_eq_lat) || ...
               isnan(latest_eq_lon) || ...
               isnan(latest_BAZ_prediction)
        
                error(['BAZ/location result is unavailable before ' ...
                       'saving the final result.']);
            end
        
            reg_start_utc = ...
                trace_start_utc ...
                + seconds(reg_start_s);
        
            reg_end_utc = ...
                trace_start_utc ...
                + seconds(reg_end_s);
        
            reg_start_utc.Format = ...
                'yyyy-MM-dd''T''HH:mm:ss.SSSSSS''Z''';
        
            reg_end_utc.Format = ...
                'yyyy-MM-dd''T''HH:mm:ss.SSSSSS''Z''';
        
            FINAL_RESULT_rows(end+1, :) = { ...
                char(P_arrival_utc), ...
                char(reg_start_utc), ...
                char(reg_end_utc), ...
                3 + c_mag, ...
                MAG_pb_predict, ...
                latest_eq_lat, ...
                latest_eq_lon, ...
                DIS_pb_predict, ...
                DEP_pb_predict, ...
                latest_BAZ_prediction ...
            };
        end
        
        fprintf(['SOURCE prediction: c_mag=%d, ' ...
                 'P-wave=%d s, ' ...
                 'MAG=%.17g, DIS=%.17g km, DEP=%.17g km\n'], ...
            c_mag, ...
            3 + c_mag, ...
            MAG_pb_predict, ...
            DIS_pb_predict, ...
            DEP_pb_predict);

        fprintf(['FV45: c_mag=%d, P-wave=%d s, ' ...
                 'start=%.1f s, end=%.1f s, npts=%d\n'], ...
            c_mag, ...
            3 + c_mag, ...
            reg_start_s, ...
            reg_end_s, ...
            npts_reg);

        % Move to the next source-parameter model
        c_mag = c_mag + 1;
    end

    % Python:
    % if c_mag == n_models:
    %     flag_magnitude = 0
    %     c_mag = 0
    if c_mag == n_models
        flag_magnitude = false;
        c_mag = 0;
    end
end



%======================================================================
    %% Post-DET background audit and state transition
    % This section is intentionally AFTER DET/new_event.  A candidate is not
    % official background until its DET label or delayed stability is known.

    if light_gate_enable
        if gate_state == GATE_EVENT_ACTIVE
            gate_candidate_features = zeros(0, 3);
            gate_candidate_safe = false(0, 1);
            if new_event == 0 && gate_background_freeze_remaining > 0
                gate_background_freeze_remaining = ...
                    gate_background_freeze_remaining - 1;
            end
            if gate_background_freeze_remaining <= 0
                if numel(gate_background_snr_db) >= ...
                        light_gate_background_windows
                    gate_state = GATE_RECOVERY;
                    gate_recovery_stable_count = 0;
                    fprintf('Adaptive Gate entered RECOVERY at t2=%.3f s.\n', t2);
                else
                    gate_state = GATE_COLD_START;
                    fprintf(['Adaptive Gate restarted COLD_START at ' ...
                        't2=%.3f s (no clean baseline retained).\n'], t2);
                end
            end

        elseif gate_state == GATE_RECOVERY
            % RECOVERY confirmation deliberately uses SNR and H only.
            recovery_stable = gate_adaptive_ready && ...
                isfinite(gate_snr_current_db) && ...
                isfinite(gate_H_current) && ...
                gate_snr_current_db <= ...
                    snr_location + light_gate_recovery_k * snr_scale && ...
                gate_H_current >= ...
                    h_location - light_gate_recovery_k * h_scale;

            if recovery_stable
                gate_recovery_stable_count = gate_recovery_stable_count + 1;
            else
                gate_recovery_stable_count = 0;
            end
            if gate_recovery_stable_count >= ...
                    light_gate_recovery_confirm_windows
                gate_state = GATE_ADAPTIVE_READY;
                gate_candidate_features = zeros(0, 3);
                gate_candidate_safe = false(0, 1);
                fprintf(['Adaptive Gate recovery confirmed at t2=%.3f s; ' ...
                    'background learning resumed.\n'], t2);
            end

        else
            % COLD_START: only DET-confirmed N can enter the queue.
            % ADAPTIVE_READY: skipped but feature-stable windows may enter;
            % periodic audit windows still require a DET-confirmed N result.
            if det_allowed
                current_background_safe = isfinite(prob_n) && ...
                    prob_n >= light_gate_noise_prob_min && ...
                    (~isfinite(prob_p) || prob_p < thr) && ...
                    (~isfinite(prob_s) || prob_s < thr) && ...
                    ~gate_background_suspicious && new_event == 0;
            else
                current_background_safe = ...
                    gate_state == GATE_ADAPTIVE_READY && ...
                    ~gate_background_suspicious;
            end

            if current_background_safe
                gate_candidate_features(end + 1, :) = [ ...
                    gate_snr_current_db, gate_H_current, ...
                    gate_energy_current_db]; %#ok<AGROW>
                gate_candidate_safe(end + 1, 1) = true; %#ok<AGROW>
            else
                % Requiring consecutive safe windows prevents a suspicious
                % window from validating an earlier overlapping candidate.
                gate_candidate_features = zeros(0, 3);
                gate_candidate_safe = false(0, 1);
            end

            if size(gate_candidate_features, 1) > ...
                    light_gate_candidate_delay_windows
                committed = gate_candidate_features(1, :);
                gate_candidate_features(1, :) = [];
                gate_candidate_safe(1, :) = [];

                gate_background_snr_db(end + 1) = committed(1);
                gate_background_H(end + 1) = committed(2);
                gate_background_energy_db(end + 1) = committed(3);
                if numel(gate_background_snr_db) > ...
                        light_gate_background_windows
                    keep_idx = numel(gate_background_snr_db) - ...
                        light_gate_background_windows + 1 : ...
                        numel(gate_background_snr_db);
                    gate_background_snr_db = ...
                        gate_background_snr_db(keep_idx);
                    gate_background_H = gate_background_H(keep_idx);
                    gate_background_energy_db = ...
                        gate_background_energy_db(keep_idx);
                end
                gate_background_updated = true;
            end
        end
    end

    gate_background_count = numel(gate_background_snr_db);
    gate_adaptive_ready = ...
        gate_background_count >= light_gate_background_windows;

    if ~det_row_already_saved
        DET_rows = [DET_rows; ...
            i3, t1, t2, idx1, idx2, length(st_pb(1).d), ...
            prob_n, prob_p, prob_s, ...
            mean_prob_p_3, mean_prob_n_buffer, ...
            eq_thr_past, eq_thr_present, new_event, ...
            gate_snr_current_db, gate_H_current, gate_pass, ...
            gate_snr_threshold_db, gate_h_threshold, ...
            gate_background_count, gate_adaptive_ready, ...
            gate_background_updated, ...
            gate_energy_current_db, gate_energy_threshold_db, ...
            gate_background_suspicious, gate_state, ...
            size(gate_candidate_features, 1), ...
            gate_background_freeze_remaining, ...
            gate_recovery_stable_count, ...
            gate_snr_jump_db, gate_snr_jump_pass, ...
            retro_backfill_count_current];

        %fprintf('%d %.3f npts=%d prob_N=%.8f prob_P=%.8f prob_S=%.8f\n', ...
          %  i3, t2, length(st_pb(1).d), prob_n, prob_p, prob_s);

        eq_thr_past = eq_thr_present;
    end
end

