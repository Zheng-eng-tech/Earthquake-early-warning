function [lat2_deg, lon2_deg] = ...
    vincenty_destination_wgs84( ...
        lat1_deg, ...
        lon1_deg, ...
        distance_km, ...
        bearing_deg)
%VINCENTY_DESTINATION_WGS84
% Vincenty direct solution on the WGS84 ellipsoid.
%
% Inputs:
%   lat1_deg    - starting latitude in degrees
%   lon1_deg    - starting longitude in degrees
%   distance_km - surface distance in kilometres
%   bearing_deg - initial bearing in degrees
%
% Outputs:
%   lat2_deg    - destination latitude in degrees
%   lon2_deg    - destination longitude in degrees

    %% WGS84 ellipsoid

    a = 6378137.0;
    f = 1.0 / 298.257223563;
    b = (1.0 - f) * a;

    %% Convert units

    phi1 = lat1_deg * pi / 180.0;
    lambda1 = lon1_deg * pi / 180.0;
    alpha1 = bearing_deg * pi / 180.0;

    distance_m = distance_km * 1000.0;

    %% Reduced latitude

    tan_U1 = (1.0 - f) * tan(phi1);

    cos_U1 = 1.0 / sqrt(1.0 + tan_U1^2);
    sin_U1 = tan_U1 * cos_U1;

    sin_alpha1 = sin(alpha1);
    cos_alpha1 = cos(alpha1);

    sigma1 = atan2( ...
        tan_U1, ...
        cos_alpha1);

    sin_alpha = ...
        cos_U1 * sin_alpha1;

    cos_sq_alpha = ...
        1.0 - sin_alpha^2;

    %% Ellipsoid coefficients

    u_sq = ...
        cos_sq_alpha ...
        * (a^2 - b^2) ...
        / b^2;

    A = ...
        1.0 ...
        + (u_sq / 16384.0) ...
        * ( ...
            4096.0 ...
            + u_sq ...
            * ( ...
                -768.0 ...
                + u_sq ...
                * ( ...
                    320.0 ...
                    - 175.0 * u_sq ...
                ) ...
            ) ...
        );

    B = ...
        (u_sq / 1024.0) ...
        * ( ...
            256.0 ...
            + u_sq ...
            * ( ...
                -128.0 ...
                + u_sq ...
                * ( ...
                    74.0 ...
                    - 47.0 * u_sq ...
                ) ...
            ) ...
        );

    %% Iteratively solve sigma

    sigma = ...
        distance_m / (b * A);

    sigma_previous = inf;

    tolerance = 1.0e-12;
    max_iterations = 200;

    iteration = 0;

    while abs(sigma - sigma_previous) > tolerance

        iteration = iteration + 1;

        if iteration > max_iterations
            error(['Vincenty destination did not converge ' ...
                   'within %d iterations.'], ...
                max_iterations);
        end

        cos_2_sigma_m = ...
            cos(2.0 * sigma1 + sigma);

        sin_sigma = sin(sigma);
        cos_sigma = cos(sigma);

        delta_sigma = ...
            B * sin_sigma * ( cos_2_sigma_m + (B / 4.0) * ( cos_sigma * ( -1.0 + 2.0 * cos_2_sigma_m^2 ) ...
                    - (B / 6.0) ...
                    * cos_2_sigma_m ...
                    * ( ...
                        -3.0 ...
                        + 4.0 * sin_sigma^2 ...
                    ) ...
                    * ( ...
                        -3.0 ...
                        + 4.0 * cos_2_sigma_m^2 ...
                    ) ...
                ) ...
            );

        sigma_previous = sigma;

        sigma = ...
            distance_m / (b * A) ...
            + delta_sigma;
    end

    %% Destination latitude

    sin_sigma = sin(sigma);
    cos_sigma = cos(sigma);

    cos_2_sigma_m = ...
        cos(2.0 * sigma1 + sigma);

    temp = ...
        sin_U1 * sin_sigma ...
        - cos_U1 ...
        * cos_sigma ...
        * cos_alpha1;

    phi2 = atan2( ...
        sin_U1 * cos_sigma ...
        + cos_U1 ...
        * sin_sigma ...
        * cos_alpha1, ...
        (1.0 - f) ...
        * sqrt( ...
            sin_alpha^2 ...
            + temp^2 ...
        ) ...
    );

    %% Difference in longitude

    lambda = atan2( ...
        sin_sigma * sin_alpha1, ...
        cos_U1 * cos_sigma ...
        - sin_U1 ...
        * sin_sigma ...
        * cos_alpha1 ...
    );

    C = ...
        (f / 16.0) ...
        * cos_sq_alpha ...
        * ( ...
            4.0 ...
            + f ...
            * ( ...
                4.0 ...
                - 3.0 * cos_sq_alpha ...
            ) ...
        );

    L = ...
        lambda ...
        - (1.0 - C) ...
        * f ...
        * sin_alpha ...
        * ( ...
            sigma ...
            + C ...
            * sin_sigma ...
            * ( ...
                cos_2_sigma_m ...
                + C ...
                * cos_sigma ...
                * ( ...
                    -1.0 ...
                    + 2.0 ...
                    * cos_2_sigma_m^2 ...
                ) ...
            ) ...
        );

    lambda2 = lambda1 + L;

    %% Convert back to degrees

    lat2_deg = phi2 * 180.0 / pi;
    lon2_deg = lambda2 * 180.0 / pi;

    % Normalize longitude to [-180, 180)
    lon2_deg = ...
        mod(lon2_deg + 180.0, 360.0) ...
        - 180.0;
end
